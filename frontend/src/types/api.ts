export type Role = 'student' | 'trainer' | 'placement' | 'admin';
export type User = { id: string; email: string; display_name: string; role: Role };
export type Session = { access_token: string; refresh_token: string; token_type: string };
export type Item = { id: string; name: string };
export type Student = { id: string; department: string; synthetic: boolean; career_role: Item | null };
export type Subscore = { name: string; score: number };
export type Topic = Subscore & { id: string; subtopics: Subscore[] };
export type History = { assessment_id: string; date: string; score: number; role: string; attempt: number; synthetic: boolean };
export type Progress = { history: History[]; latest: History | null; topics: Topic[] };
export type Question = { id: string; position: number; text: string; difficulty: string; selected?: string | null;
  options: { label: string; text: string }[] };
export type Exam = { id: string; mode: string; attempt: number; status: string; scheduled_at: string | null; questions: Question[] };
export type AssessmentListItem = Omit<Exam, 'questions' | 'mode'> & { taken_at: string | null };
export type Result = { assessment_id: string; readiness: number | null; threshold: number;
  coverage: { assessed: string[]; unassessed: string[]; answered_questions: number; assigned_questions: number } | null;
  topics: Topic[] };
export type Prediction = { value: number; algorithm: string; model_id: string };
export type Predictions = { status: string; classification: Prediction | null; regression: Prediction | null;
  classification_status?: string; synthetic?: boolean };
export type Roadmap = { id: string; assessment_id: string; current_readiness: number; target_role: string;
  duration_weeks: number; priority_skills: string[]; weekly_hours: number; explanation: string;
  resources: { id: string; title: string; url: string }[];
  weekly_plan: { week: number; focus: string; hours: number; tasks: string[] }[];
  tasks: { id: string; title: string; week: number; completed: boolean }[];
  practice_tasks: string[]; reassessment_milestones: string[] };
export type RoadmapResult = { status: string; roadmap: Roadmap | null };
